test("an AI Wikipedia description overrides otherwise human-looking metadata; concert history pulls the other way", () => {
  const looksHuman = base({
    albums: [{ id: "1", title: "A", releaseDate: "2026-06-01", trackCount: 10 }],
    musicBrainz: { artistFound: true, urlCount: 10, hasBackground: true, recordingFound: true, creditCount: 3 },
  });
  const ai = scoreArtist({ ...looksHuman, web: { wikipedia: wiki({ aiMentioned: true, aiDescribed: true }) } }, { now: new Date("2026-10-01") });
  assert.equal(ai.verdict, "likely-ai");

  // Wikipedia only covers it inside an AI article: not decisive, but clearly pushed up
  const redirect = scoreArtist(
    { ...looksHuman, web: { wikipedia: wiki({ ownArticle: false, aiMentioned: true }) } },
    { now: new Date("2026-10-01") },
  );
  assert.ok(redirect.score! > 0.45, `expected at least suspicious, got ${redirect.score}`);

  // a prolific act with a long concert history is still a human act
  const prolific = base({
    albums: Array.from({ length: 50 }, (_, i) => ({
      id: String(i), title: `A${i}`, trackCount: 10,
      releaseDate: new Date(Date.parse("2026-10-01") - i * 5 * 86400000).toISOString().slice(0, 10),
    })),
    musicBrainz: { artistFound: true, urlCount: 5, hasBackground: true, recordingFound: true, creditCount: 4 },
    web: { live: { setlists: 80 }, wikipedia: wiki({}) },
  });
  assert.equal(scoreArtist(prolific, { now: new Date("2026-10-01") }).verdict, "likely-human");
});

