test("Wikipedia: own musician article, AI act, redirect cases, disambiguation and errors", async () => {
  const human = new Wikipedia(
    fakeFetch({ "/Rick_Astley": { body: { type: "standard", title: "Rick Astley", description: "English singer (born 1966)", extract: "Richard Paul Astley is an English singer, songwriter." } } }),
  );
  assert.deepEqual(await human.lookup("Rick Astley"), {
    found: true, title: "Rick Astley", description: "English singer (born 1966)", ownArticle: true, aiMentioned: false, aiDescribed: false,
  });

  const ai = new Wikipedia(
    fakeFetch({ "/Breaking_Rust": { body: { type: "standard", title: "Breaking Rust", description: "AI-generated country music artist", extract: "Breaking Rust is an AI-generated country music project." } } }),
  );
  const a = await ai.lookup("Breaking Rust");
  assert.ok(a.found && a.ownArticle && a.aiMentioned && a.aiDescribed);

  // "Beatles" redirecting to "The Beatles" is still the act's own article
  const the = new Wikipedia(fakeFetch({ "/Beatles": { body: { type: "standard", title: "The Beatles", description: "English rock band", extract: "The Beatles were an English rock band." } } }));
  assert.equal((await the.lookup("Beatles")).ownArticle, true);

  // exact title redirects to a broader AI article: counts, but not as the act's own page
  const redirected = new Wikipedia(
    fakeFetch({ "/The_Velvet_Sundown": { body: { type: "standard", title: "AI slop", description: "Low-quality AI-generated digital content", extract: "AI slop is content made with generative AI." } } }),
  );
  const r = await redirected.lookup("The Velvet Sundown");
  assert.ok(r.found && !r.ownArticle && r.aiMentioned);

  // redirect to an unrelated non-AI article, a disambiguation page, a non-music page, and outright errors: nothing found
  for (const body of [
    { type: "standard", title: "Some Other Topic", description: "A thing", extract: "Unrelated." },
    { type: "disambiguation", title: "Twin", description: "Topics", extract: "Twin may refer to" },
    { type: "standard", title: "Twin", description: "Fruit", extract: "A kind of fruit." },
  ]) {
    assert.equal((await new Wikipedia(fakeFetch({ "/Twin": { body } })).lookup("Twin")).found, false);
  }
  assert.equal((await new Wikipedia(fakeFetch({ "/X": { status: 500, body: {} } })).lookup("X")).found, false);
});

