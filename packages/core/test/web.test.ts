import { test } from "node:test";
import assert from "node:assert/strict";
import {
  Wikipedia, usableImage, SetlistFm, YouTube, lookupWebPresence, looksAiMade, scoreArtist,
  wikipedia, livePerformances, youtubeLive, externalPresence,
  type ArtistProfile, type WikipediaInfo,
} from "../src/index.js";

type Reply = { status?: number; body: unknown };
/** Fake fetch keyed on a URL substring; unknown URLs 404. */
const fakeFetch = (routes: Record<string, Reply>) =>
  (async (url: string) => {
    const key = Object.keys(routes).find((k) => String(url).includes(k));
    const r = key ? routes[key]! : { status: 404, body: { title: "Not found" } };
    const status = r.status ?? 200;
    return { ok: status < 400, status, statusText: "", json: async () => r.body } as Response;
  }) as typeof fetch;

const base = (over: Partial<ArtistProfile> = {}): ArtistProfile => ({ key: "deezer:1", name: "T", albums: [], topTracks: [], ...over });
const wiki = (over: Partial<WikipediaInfo>): WikipediaInfo => ({ found: true, ownArticle: true, aiMentioned: false, aiDescribed: false, ...over });

test("looksAiMade catches real AI-act descriptions and ignores human or merely virtual acts", () => {
  assert.ok(looksAiMade("AI-generated country music artist"));
  assert.ok(looksAiMade("Artificially generated R&B singer"));
  assert.ok(looksAiMade("Xania Monet is an artificial intelligence music project generated by Telisha Jones"));
  assert.ok(looksAiMade("a band whose songs were made with Suno"));
  assert.equal(looksAiMade("English singer (born 1966)"), false);
  assert.equal(looksAiMade("Gorillaz are a British virtual band created by Damon Albarn"), false);
  assert.equal(looksAiMade("An artist who says she never uses AI tools"), false);
});

test("Wikipedia: own musician article, AI act, redirect cases, disambiguation and errors", async () => {
  const human = new Wikipedia(
    fakeFetch({ "/Rick_Astley": { body: { type: "standard", title: "Rick Astley", description: "English singer (born 1966)", extract: "Richard Paul Astley is an English singer, songwriter." } } }),
  );
  assert.deepEqual(await human.lookup("Rick Astley"), {
    found: true, title: "Rick Astley", description: "English singer (born 1966)", ownArticle: true, aiMentioned: false, aiDescribed: false,
  });

  const ai = new Wikipedia(
    fakeFetch({ "/Breaking_Rust": { body: { type: "standard", title: "Breaking Rust", description: "AI-generated country music artist", extract: "Breaking Rust is an AI-generated country music project." } } }),
  );
  const a = await ai.lookup("Breaking Rust");
  assert.ok(a.found && a.ownArticle && a.aiMentioned && a.aiDescribed);

  // "Beatles" redirecting to "The Beatles" is still the act's own article
  const the = new Wikipedia(fakeFetch({ "/Beatles": { body: { type: "standard", title: "The Beatles", description: "English rock band", extract: "The Beatles were an English rock band." } } }));
  assert.equal((await the.lookup("Beatles")).ownArticle, true);

  // exact title redirects to a broader AI article: counts, but not as the act's own page
  const redirected = new Wikipedia(
    fakeFetch({ "/The_Velvet_Sundown": { body: { type: "standard", title: "AI slop", description: "Low-quality AI-generated digital content", extract: "AI slop is content made with generative AI." } } }),
  );
  const r = await redirected.lookup("The Velvet Sundown");
  assert.ok(r.found && !r.ownArticle && r.aiMentioned);

  // redirect to an unrelated non-AI article, a disambiguation page, a non-music page, and outright errors: nothing found
  for (const body of [
    { type: "standard", title: "Some Other Topic", description: "A thing", extract: "Unrelated." },
    { type: "disambiguation", title: "Twin", description: "Topics", extract: "Twin may refer to" },
    { type: "standard", title: "Twin", description: "Fruit", extract: "A kind of fruit." },
  ]) {
    assert.equal((await new Wikipedia(fakeFetch({ "/Twin": { body } })).lookup("Twin")).found, false);
  }
  assert.equal((await new Wikipedia(fakeFetch({ "/X": { status: 500, body: {} } })).lookup("X")).found, false);
});

test("SetlistFm and YouTube providers parse responses", async () => {
  const sl = new SetlistFm("k", fakeFetch({ "/artist/abc/setlists": { body: { total: 42 } } }));
  assert.equal(await sl.setlistCount("abc"), 42);
  assert.equal(await new SetlistFm("k", fakeFetch({})).setlistCount("none"), 0);

  const yt = new YouTube(
    "k",
    fakeFetch({
      "youtube/v3/search": {
        body: {
          items: [
            { snippet: { title: "Nina Lane - Live at Glastonbury 2024", channelId: "c1" } },
            { snippet: { title: "Nina Lane live concert full set", channelId: "c2" } },
            { snippet: { title: "Nina Lane - live in Berlin", channelId: "c2" } }, // same channel: counted once
            { snippet: { title: "Nina Lane - Official Lyric Video", channelId: "c3" } }, // not live
            { snippet: { title: "Someone Else live concert", channelId: "c4" } }, // not this artist
          ],
        },
      },
    }),
  );
  assert.equal(await yt.liveVideos("Nina Lane"), 2);
});

test("lookupWebPresence: optional sources are skipped without keys and failures stay isolated", async () => {
  const f = fakeFetch({ "/Rick_Astley": { body: { type: "standard", title: "Rick Astley", description: "English singer", extract: "An English singer." } } });
  const noKeys = await lookupWebPresence("Rick Astley", { fetch: f, mbid: "abc" });
  assert.equal(noKeys.live, undefined);
  assert.equal(noKeys.youtube, undefined);
  assert.equal(noKeys.wikipedia?.found, true);

  // setlist.fm blows up (500): Wikipedia and YouTube still come back
  const f2 = fakeFetch({
    "/Rick_Astley": { body: { type: "standard", title: "Rick Astley", description: "English singer", extract: "An English singer." } },
    "api.setlist.fm": { status: 500, body: {} },
    "youtube/v3/search": { body: { items: [] } },
  });
  const mixed = await lookupWebPresence("Rick Astley", { fetch: f2, mbid: "abc", setlistFmKey: "k", youtubeKey: "k" });
  assert.equal(mixed.live, undefined);
  assert.deepEqual(mixed.youtube, { liveVideos: 0 });
  assert.equal(mixed.wikipedia?.found, true);
});

test("signals: wikipedia, live performances, youtube", () => {
  const sig = (s: any, web: ArtistProfile["web"]) => s(base({ web }), new Date());
  assert.equal(sig(wikipedia, undefined).score, null);
  assert.equal(sig(wikipedia, { wikipedia: wiki({ found: false }) }).score, null);
  assert.equal(sig(wikipedia, { wikipedia: wiki({}) }).score, 0.1);
  const own = sig(wikipedia, { wikipedia: wiki({ aiMentioned: true, aiDescribed: true }) });
  assert.ok(own.decisive && own.score >= 0.95);
  const leadOnly = sig(wikipedia, { wikipedia: wiki({ aiMentioned: true, aiDescribed: false }) });
  assert.ok(!leadOnly.decisive && leadOnly.score >= 0.85);

  assert.equal(sig(livePerformances, undefined).score, null);
  assert.ok(sig(livePerformances, { live: { setlists: 0 } }).score >= 0.5);
  assert.ok(sig(livePerformances, { live: { setlists: 30 } }).score <= 0.03);
  assert.ok(sig(livePerformances, { live: { setlists: 1 } }).score > sig(livePerformances, { live: { setlists: 10 } }).score);

  assert.equal(sig(youtubeLive, undefined).score, null);
  assert.ok(sig(youtubeLive, { youtube: { liveVideos: 0 } }).score >= 0.5);
  assert.ok(sig(youtubeLive, { youtube: { liveVideos: 8 } }).score <= 0.05);
});

test("externalPresence scales with links instead of jumping to 25%", () => {
  const mb = (urlCount: number, hasBackground = false) =>
    externalPresence(base({ musicBrainz: { artistFound: true, urlCount, hasBackground, recordingFound: false, creditCount: 0 } }), new Date()).score!;
  assert.ok(mb(10) < 0.06, "many links, no background info: near zero");
  assert.ok(mb(4) < 0.12);
  assert.ok(mb(0) > mb(1) && mb(1) > mb(3) && mb(3) > mb(6));
  assert.ok(mb(6, true) < mb(6, false));
});

test("an AI Wikipedia description overrides otherwise human-looking metadata; concert history pulls the other way", () => {
  const looksHuman = base({
    albums: [{ id: "1", title: "A", releaseDate: "2026-06-01", trackCount: 10 }],
    musicBrainz: { artistFound: true, urlCount: 10, hasBackground: true, recordingFound: true, creditCount: 3 },
  });
  const ai = scoreArtist({ ...looksHuman, web: { wikipedia: wiki({ aiMentioned: true, aiDescribed: true }) } }, { now: new Date("2026-10-01") });
  assert.equal(ai.verdict, "likely-ai");

  // Wikipedia only covers it inside an AI article: not decisive, but clearly pushed up
  const redirect = scoreArtist(
    { ...looksHuman, web: { wikipedia: wiki({ ownArticle: false, aiMentioned: true }) } },
    { now: new Date("2026-10-01") },
  );
  assert.ok(redirect.score! > 0.45, `expected at least suspicious, got ${redirect.score}`);

  // a prolific act with a long concert history is still a human act
  const prolific = base({
    albums: Array.from({ length: 50 }, (_, i) => ({
      id: String(i), title: `A${i}`, trackCount: 10,
      releaseDate: new Date(Date.parse("2026-10-01") - i * 5 * 86400000).toISOString().slice(0, 10),
    })),
    musicBrainz: { artistFound: true, urlCount: 5, hasBackground: true, recordingFound: true, creditCount: 4 },
    web: { live: { setlists: 80 }, wikipedia: wiki({}) },
  });
  assert.equal(scoreArtist(prolific, { now: new Date("2026-10-01") }).verdict, "likely-human");
});

test("usableImage keeps real Deezer photos and drops placeholders and foreign hosts", () => {
  const real = "https://cdn-images.dzcdn.net/images/artist/2a1b/500x500-000000-80-0-0.jpg";
  assert.equal(usableImage(real), real);
  assert.equal(usableImage("https://cdn-images.dzcdn.net/images/artist//500x500-000000-80-0-0.jpg"), undefined, "empty hash = no photo");
  assert.equal(usableImage("https://evil.example.com/x.jpg"), undefined);
  assert.equal(usableImage("http://cdn-images.dzcdn.net/images/artist/2a1b/x.jpg"), undefined, "https only");
  assert.equal(usableImage("javascript:alert(1)"), undefined);
  assert.equal(usableImage(undefined), undefined);
});
